def read_chunks(file_path, chunk_size=100000):

    chunk_counter = 0

    for chunk in pd.read_csv(
        file_path,
        sep=';',
        chunksize=chunk_size,
        low_memory=False
    ):

        chunk_counter += 1

        print(
            f"Reading Chunk {chunk_counter} | Rows: {len(chunk)}"
        )

        yield chunk

