def read_chunks(file_path, chunk_size=100000):

    for chunk in pd.read_csv(
        file_path,
        sep=';',
        chunksize=chunk_size,
        low_memory=False
    ):
        yield chunk

question_mark_counts = {}

for chunk in read_chunks("/content/household_power_consumption dataset.txt"):

    chunk_missing = (chunk == '?').sum()

    for column, count in chunk_missing.items():

        question_mark_counts[column] = (
            question_mark_counts.get(column, 0)
            + count
        )

question_mark_counts

total_rows = 2075259

for column, count in question_mark_counts.items():

    percentage = (count / total_rows) * 100

    print(
        f"{column}: {percentage:.4f}%"
    )

total_missing_rows = 0

for chunk in read_chunks("/content/household_power_consumption dataset.txt"):

    missing_rows = (
        (chunk == '?')
        .any(axis=1)
        .sum()
    )

    total_missing_rows += missing_rows

print("Rows containing missing values:", total_missing_rows)