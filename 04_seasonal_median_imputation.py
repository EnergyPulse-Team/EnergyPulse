import pandas as pd
import numpy as np

file_path = "/content/household_power_consumption dataset.txt"

first_chunk = pd.read_csv(
    file_path,
    sep=';',
    nrows=100000,
    low_memory=False
)

(first_chunk == '?').sum()

first_chunk = first_chunk.replace('?', np.nan)

first_chunk.isnull().sum()

first_chunk.dtypes

numeric_columns = [
    'Global_active_power',
    'Global_reactive_power',
    'Voltage',
    'Global_intensity',
    'Sub_metering_1',
    'Sub_metering_2',
    'Sub_metering_3'
]

for col in numeric_columns:
    first_chunk[col] = pd.to_numeric(
        first_chunk[col],
        errors='coerce'
    )

first_chunk.dtypes

first_chunk["Datetime"] = pd.to_datetime(
    first_chunk["Date"] + " " + first_chunk["Time"],
    format="%d/%m/%Y %H:%M:%S"
)

first_chunk[["Date", "Time", "Datetime"]].head()

first_chunk["Datetime"].isnull().sum()

first_chunk.isnull().sum()

for col in numeric_columns:

    median_value = first_chunk[col].median()

    first_chunk[col] = first_chunk[col].fillna(
        median_value
    )

first_chunk.isnull().sum()

first_chunk["Hour"] = first_chunk["Datetime"].dt.hour

first_chunk["Month"] = first_chunk["Datetime"].dt.month

first_chunk["DayOfWeek"] = first_chunk["Datetime"].dt.dayofweek

first_chunk[
    ["Datetime", "Hour", "Month", "DayOfWeek"]
].head()

first_chunk[["Hour", "Month", "DayOfWeek"]].describe()

hourly_medians = first_chunk.groupby(
    "Hour"
)[numeric_columns].median()

hourly_medians.head()

test_chunk = pd.read_csv(
    file_path,
    sep=';',
    nrows=100000,
    low_memory=False
)

test_chunk = test_chunk.replace('?', np.nan)

for col in numeric_columns:
    test_chunk[col] = pd.to_numeric(
        test_chunk[col],
        errors='coerce'
    )

test_chunk["Datetime"] = pd.to_datetime(
    test_chunk["Date"] + " " + test_chunk["Time"],
    format="%d/%m/%Y %H:%M:%S"
)

test_chunk["Hour"] = test_chunk["Datetime"].dt.hour

test_chunk.isnull().sum()

for col in numeric_columns:

    test_chunk[col] = test_chunk.groupby(
        "Hour"
    )[col].transform(
        lambda x: x.fillna(x.median())
    )

test_chunk.isnull().sum()

rows_before = 100000
rows_after = len(test_chunk)

print("Rows Before:", rows_before)
print("Rows After :", rows_after)

